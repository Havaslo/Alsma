export const ensureDefaultAgentPlaybook = async (database: Database) => {
  await Promise.all([
    ...[...defaultScenarios, ...defaultVoiceScenarios].map(async (item) => {
      const existing = await database.client.agentScenario.findFirst({
        where: { title: item.title },
        select: { action: true, id: true, page: true, response: true },
      });
      if (!existing) {
        await database.client.agentScenario.create({ data: item });
      } else if (
        previousDefaultScenarioResponses[item.title] === existing.response
      ) {
        // Refresh only unchanged defaults, preserving administrator edits.
        await database.client.agentScenario.update({
          data: { response: item.response },
          where: { id: existing.id },
        });
      } else if (
        "action" in item &&
        item.title === "Акции и скидки" &&
        existing.action === "answer" &&
        existing.page === null &&
        existing.response === item.response
      ) {
        // Migrate the previously seeded offers scenario without overwriting admin edits.
        await database.client.agentScenario.update({
          data: { action: item.action, page: item.page },
          where: { id: existing.id },
        });
      }
    }),
    ...[...defaultTransferRules, ...defaultVoiceTransferRules].map(
      async (item) => {
        const existing = await database.client.agentTransferRule.findFirst({
          where: { title: item.title },
          select: { condition: true, id: true },
        });
        if (!existing) {
          await database.client.agentTransferRule.create({ data: item });
        } else if (
          previousDefaultTransferConditions[item.title] === existing.condition
        ) {
          // Refresh only unchanged defaults, preserving administrator edits.
          await database.client.agentTransferRule.update({
            data: { condition: item.condition },
            where: { id: existing.id },
          });
        }
      },
    ),
  ]);
};
