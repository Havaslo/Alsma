export const getVoiceGreetingInstruction = (now = new Date()) => {
  const hour = Number(
    new Intl.DateTimeFormat("en", {
      timeZone: "Europe/Moscow",
      hour: "2-digit",
      hourCycle: "h23",
    }).format(now),
  );
  const greeting =
    hour >= 5 && hour < 12
      ? "Доброе утро"
      : hour >= 12 && hour < 18
        ? "Добрый день"
        : hour >= 18 && hour < 23
          ? "Добрый вечер"
          : "Доброй ночи";
  return `Текущее время по Москве: ${new Intl.DateTimeFormat("ru-RU", {
    timeZone: "Europe/Moscow",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).format(
    now,
  )}. Начни новый входящий разговор фразой «${greeting}» и сразу коротко представься.`;
};

export const getVoiceStayDateInstruction = (now = new Date()) => {
  const currentYear = new Intl.DateTimeFormat("en", {
    timeZone: "Europe/Moscow",
    year: "numeric",
  }).format(now);
  return `Текущий год по Москве для дат проживания — ${currentYear}. Если гость назвал даты без года, используй этот год и не спрашивай год: гость сам уточнит, если имеет в виду другой. Если дата этого года уже прошла, коротко уточни актуальные даты, не спрашивая отдельно год.`;
};

